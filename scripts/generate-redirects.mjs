/**
 * Generates public/_redirects.
 *
 * Why this exists: Cloudflare's own trailing-slash handling issues a **307**
 * (temporary). Google treats a 307 as "keep checking the old URL", so link
 * equity never fully consolidates onto the canonical slash version and the URLs
 * sit permanently in Search Console's "Page with redirect" bucket. Only an
 * explicit _redirects rule can return a 301, and `assets.html_handling` cannot
 * be configured to do it.
 *
 * Rules are emitted ONE PER KNOWN PATH on purpose. A wildcard such as
 * `/calculators/:slug  /calculators/:slug/  301` risks re-matching its own
 * target and looping, which would take the whole site down. Explicit sources
 * never carry a trailing slash and every target always does, so a target can
 * never match a source. The script asserts that before writing.
 *
 * Run automatically by `npm run build`. Safe to run by hand:
 *   node scripts/generate-redirects.mjs
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const read = (p) => readFileSync(join(root, p), 'utf8');

const calculators = [...read('lib/calculators-registry.ts').matchAll(/id: '([a-z0-9-]+)'/g)].map((m) => m[1]);
const guides = [...read('lib/guides-data.ts').matchAll(/^ {4}slug: '([a-z0-9-]+)'/gm)].map((m) => m[1]);
const categories = ['tax', 'investment', 'savings', 'loans', 'business', 'health'];
const statics = ['about', 'contact', 'privacy-policy', 'terms-of-service'];

if (calculators.length === 0 || guides.length === 0) {
  throw new Error('generate-redirects: parsed 0 calculators or 0 guides - check the source files');
}

/** Hand-maintained rules. Order matters: the first match wins. */
const fixed = [
  ['/calculators/*/__next.*.txt', '/calculators/:splat/', '200'],
  ['/guides/*/__next.*.txt', '/guides/:splat/', '200'],
  ['/__next.*.txt', '/', '200'],
  // /calculators/ has no index page
  ['/calculators/', '/', '301'],
  ['/calculators', '/', '301'],
  // Consolidated duplicates (2026-10-02). Both spellings point straight at the
  // final target so neither produces a redirect chain.
  ['/guides/sip-vs-lumpsum/', '/calculators/sip-vs-lumpsum/', '301'],
  ['/guides/sip-vs-lumpsum', '/calculators/sip-vs-lumpsum/', '301'],
  ['/guides/how-to-save-tax-on-salary/', '/guides/tax-saving-guide-2025-26/', '301'],
  ['/guides/how-to-save-tax-on-salary', '/guides/tax-saving-guide-2025-26/', '301'],
];

const slashed = [
  '/guides',
  ...statics.map((s) => `/${s}`),
  ...categories.map((c) => `/calculators/${c}`),
  ...calculators.map((c) => `/calculators/${c}`),
  ...guides.map((g) => `/guides/${g}`),
];

const fixedSources = new Set(fixed.map(([s]) => s));
const generated = [];
const seen = new Set(fixedSources);
for (const path of slashed) {
  if (seen.has(path)) continue; // a hand-maintained rule already covers it
  seen.add(path);
  generated.push([path, `${path}/`, '301']);
}

// ---- safety assertions: a bad rule here takes the site down ----------------
const all = [...fixed, ...generated];
const sources = all.map(([s]) => s);
const targets = new Set(all.map(([, t]) => t));

const dupes = sources.filter((s, i) => sources.indexOf(s) !== i);
if (dupes.length) throw new Error(`generate-redirects: duplicate sources: ${dupes.join(', ')}`);

const loops = all.filter(([s, t]) => s === t);
if (loops.length) throw new Error(`generate-redirects: self-referencing rule: ${loops[0].join(' ')}`);

const crossed = sources.filter((s) => targets.has(s) && !s.includes('*'));
if (crossed.length) {
  throw new Error(`generate-redirects: these are both a source and a target (loop risk): ${crossed.join(', ')}`);
}

// ---- emit ------------------------------------------------------------------
const pad = (rows) => {
  const w = Math.max(...rows.map(([s]) => s.length));
  return rows.map(([s, t, c]) => `${s.padEnd(w)}  ${t}  ${c}`).join('\n');
};

const out = `# GENERATED by scripts/generate-redirects.mjs - do not edit by hand.
# Re-run with: node scripts/generate-redirects.mjs
#
# Cloudflare's built-in trailing-slash handling returns a 307 (temporary), which
# tells Google to keep the non-slash URL around and blocks consolidation. These
# explicit rules return 301 instead. One rule per known path, never a wildcard:
# a pattern that re-matches its own target would loop and take the site down.

# --- Next.js App Router RSC payload fallback --------------------------------
${pad(fixed.slice(0, 3))}

# --- index pages and consolidated duplicates --------------------------------
${pad(fixed.slice(3))}

# --- trailing-slash canonicalisation (${generated.length} rules, generated) ---
${pad(generated)}
`;

writeFileSync(join(root, 'public/_redirects'), out, 'utf8');
console.log(
  `generate-redirects: ${all.length} rules written ` +
    `(${calculators.length} calculators, ${guides.length} guides, ${generated.length} generated)`
);
